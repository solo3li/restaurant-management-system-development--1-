def _is_minio_reachable(endpoint, timeout=0.3):
    try:
        from urllib.parse import urlparse
        import socket
        parsed = urlparse(endpoint)
        host = parsed.hostname or "127.0.0.1"
        port = parsed.port or (443 if parsed.scheme == "https" else 80)
        sock = socket.create_connection((host, port), timeout=timeout)
        sock.close()
        return True
    except Exception:
        return False

# In standalone runs (outside Docker container), resolve http://minio:9000 to host port 9200 if reachable
